#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"
ENV_FILE="${ENV_FILE:-.env}"

fail() {
  echo "Preflight failed: $*" >&2
  exit 1
}

warn() {
  echo "Preflight warning: $*" >&2
}

[[ -f "$ENV_FILE" ]] || fail "Missing $ENV_FILE. Copy .env.example to .env and fill every production value."

if grep -Eq '^(ADMIN_PASSWORD_HASH|OPERATOR_PASSWORD_HASH|MAIN_PASSWORD_HASH|CAMPUS_B_PASSWORD_HASH|CAMPUS_C_PASSWORD_HASH)=\$2' "$ENV_FILE"; then
  fail "bcrypt hashes in .env must be wrapped in single quotes, for example ADMIN_PASSWORD_HASH='\$2b\$12\$...'."
fi

set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a

required=(
  PUBLIC_IP
  APP_DOMAIN
  RTC_DOMAIN
  TURN_DOMAIN
  STREAM_DOMAIN
  MONITOR_DOMAIN
  MONITOR_ALLOWED_CIDR
  APP_BASE_URL
  NEXT_PUBLIC_RTC_URL
  RTC_API_URL
  NEXT_PUBLIC_STREAM_LLHLS_BASE_URL
  RELAY_SRT_PUBLISH_URL
  SESSION_SECRET
  RTC_API_KEY
  RTC_API_SECRET
  TURN_STATIC_AUTH_SECRET
  ADMIN_PASSWORD_HASH
  OPERATOR_PASSWORD_HASH
  MAIN_PASSWORD_HASH
  CAMPUS_B_PASSWORD_HASH
  CAMPUS_C_PASSWORD_HASH
  GRAFANA_ADMIN_USER
  GRAFANA_ADMIN_PASSWORD
  GREETING_MODE_NAME
  PROGRAM_MODE_NAME
  RTC_SERVER_IMAGE
  RTC_INGRESS_IMAGE
  RTC_EGRESS_IMAGE
  STREAMING_RELAY_IMAGE
)

for name in "${required[@]}"; do
  value="${!name:-}"
  [[ -n "$value" ]] || fail "$name is missing."
  [[ "$value" != CHANGE_ME* ]] || fail "$name still uses a CHANGE_ME placeholder."
done

for name in RTC_SERVER_IMAGE RTC_INGRESS_IMAGE RTC_EGRESS_IMAGE STREAMING_RELAY_IMAGE; do
  value="${!name}"
  [[ "$value" != *":latest" && "$value" != "latest" ]] || fail "$name must be pinned to a version tag or digest, not latest."
done

for name in ADMIN_PASSWORD_HASH OPERATOR_PASSWORD_HASH MAIN_PASSWORD_HASH CAMPUS_B_PASSWORD_HASH CAMPUS_C_PASSWORD_HASH; do
  value="${!name}"
  [[ "$value" == \$2* ]] || fail "$name must be a bcrypt hash generated by npm --prefix campus-connect-web run hash-password."
done

[[ "${#SESSION_SECRET}" -ge 48 ]] || fail "SESSION_SECRET should be at least 48 characters. Generate it with: openssl rand -base64 48"
[[ "$APP_BASE_URL" == https://* ]] || fail "APP_BASE_URL must use https:// for production."
[[ "$NEXT_PUBLIC_RTC_URL" == wss://* ]] || fail "NEXT_PUBLIC_RTC_URL must use wss:// for production."
[[ "$RTC_API_URL" == http://* || "$RTC_API_URL" == https://* ]] || fail "RTC_API_URL must be an http:// or https:// URL."
[[ "$RTC_API_URL" != *"rtc-server"* ]] || fail "RTC_API_URL must not use rtc-server in this host-network deployment. Use http://host.docker.internal:7880."
[[ "$RTC_API_URL" != http://127.* && "$RTC_API_URL" != http://localhost* ]] || fail "RTC_API_URL points at the web container itself. Use http://host.docker.internal:7880 for this deployment."
[[ "$NEXT_PUBLIC_STREAM_LLHLS_BASE_URL" == https://* ]] || fail "NEXT_PUBLIC_STREAM_LLHLS_BASE_URL must use https:// for production."
[[ "$RELAY_SRT_PUBLISH_URL" == srt://* ]] || fail "RELAY_SRT_PUBLISH_URL must be an srt:// URL."
[[ "$MONITOR_ALLOWED_CIDR" != "0.0.0.0/0" && "$MONITOR_ALLOWED_CIDR" != "::/0" ]] || fail "MONITOR_ALLOWED_CIDR must be restricted to office/VPN IPs."

for cmd in docker envsubst openssl; do
  command -v "$cmd" >/dev/null 2>&1 || fail "$cmd is not installed. Run sudo ./scripts/install.sh first."
done

if [[ "$PUBLIC_IP" =~ ^127\. || "$PUBLIC_IP" == "localhost" ]]; then
  fail "PUBLIC_IP must be the AWS Elastic IP, not localhost."
fi

if [[ "${1:-}" != "--skip-compose" ]]; then
  docker compose config -q || fail "docker compose config validation failed."
fi

warn "Run a full rehearsal before Sunday production; this script verifies deployment configuration, not WAN quality."
echo "Campus Connect production preflight passed."
